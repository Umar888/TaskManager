@Composable
fun AppTheme(
    settings: AppSettings = AppSettings(),
    content: @Composable () -> Unit
) {
    val isDark = when (settings.themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }
    val context = LocalContext.current
    val colorScheme = when {
        settings.dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (isDark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        else -> generateColorScheme(settings.seedColor, if (isDark) DarkColors else LightColors, isDark)
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = typography,
        content = content
    )
}

/** Semantic colours that aren't part of the M3 scheme, tuned per theme. */
object TaskColors {
    @Composable
    fun priority(priority: TaskPriority): Color {
        val dark = MaterialTheme.colorScheme.surface.luminance() < 0.5f
        return when (priority) {
            TaskPriority.HIGH -> if (dark) Color(0xFFFF8A80) else Color(0xFFD32F2F)
            TaskPriority.MEDIUM -> if (dark) Color(0xFFFFCC80) else Color(0xFFEF6C00)
            TaskPriority.LOW -> if (dark) Color(0xFFA5D6A7) else Color(0xFF2E7D32)
        }
    }

    @Composable
    fun status(status: TaskStatus): Color {
        val dark = MaterialTheme.colorScheme.surface.luminance() < 0.5f
        return when (status) {
            TaskStatus.PENDING -> MaterialTheme.colorScheme.onSurfaceVariant
            TaskStatus.IN_PROGRESS -> if (dark) Color(0xFF90CAF9) else Color(0xFF1565C0)
            TaskStatus.COMPLETED -> if (dark) Color(0xFFA5D6A7) else Color(0xFF2E7D32)
        }
    }
}
